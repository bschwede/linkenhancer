#!/usr/bin/env node
// Generates the enhanced-links parameter reference fragment for the documentation site.
// Reads the target configuration from le-config.js (Single Source) and merges
// EN i18n texts from le-i18n-en.json (exported by export-le-i18n.php).
//
// Output: stdout (fragment, no frontmatter)
// Target: assets/includes/linkenhancer/le-link-parameters.md (in wt-modules)
//
// Run: node util/generate-link-params.mjs > /path/to/assets/includes/linkenhancer/le-link-parameters.md
//
// Phase 2 pre-step (regenerate EN texts after changing LinkEnhancerUtils.php):
//   php util/export-le-i18n.php > util/le-i18n-en.json

import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { getLETargetCfg, getLEOptions } from '../resources/js/src/le-config.js';
import { getLErecTypes } from '../resources/js/src/le-xref-parser.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const i18nPath = join(__dirname, 'le-i18n-en.json');

let i18n = {};
try {
    i18n = JSON.parse(readFileSync(i18nPath, 'utf8'));
} catch {
    process.stderr.write('WARNING: le-i18n-en.json not found — using raw keys (Phase 1 mode)\n');
}

const options = Object.assign(getLEOptions(), {
    I18N: i18n,
    baseurl: 'https://example.org/tree/main',
    tree: 'main',
    urlmode: 'standard',
});

const cfg = getLETargetCfg(options, getLErecTypes);

const rows = [];

for (const [key, target] of Object.entries(cfg)) {
    const name = target.name
        .replace(/ - \$ID/, '')
        .replace(/%s/, '')
        .replace(/ {2,}/g, ' ')
        .trim();

    if (target.help && target.help.length > 0) {
        for (const h of target.help) {
            const desc = h.n
                .replace(/%s/, '')
                .replace(/ {2,}/g, ' ')
                .trim();
            rows.push({ key, name, syntax: `${key}=${h.e}`, desc });
        }
    } else {
        rows.push({ key, name, syntax: `${key}=ID`, desc: '' });
    }
}

// Deduplicate: if a key has multiple rows, only show name on the first.
const seen = new Set();
const finalRows = rows.map(r => {
    const first = !seen.has(r.key);
    seen.add(r.key);
    return { ...r, name: first ? r.name : '' };
});

// Emit fragment (no frontmatter).
console.log('_Auto-generated by `util/generate-link-params.mjs` — do not edit manually._');
console.log('');
console.log('| Key | Name | Syntax | Description |');
console.log('| --- | --- | --- | --- |');

for (const r of finalRows) {
    const nameCol = r.name.replace(/\|/g, '\\|');
    const descCol = r.desc
        .replace(/<a href="([^"]+)">([^<]+)<\/a>/g, '[$2]($1)')
        .replace(/\|/g, '\\|');
    const syntaxCol = `\`${r.syntax}\``;
    console.log(`| \`${r.key}\` | ${nameCol} | ${syntaxCol} | ${descCol} |`);
}
