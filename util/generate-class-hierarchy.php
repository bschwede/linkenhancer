#!/usr/bin/env php
<?php
// Generates the class-hierarchy fragment for the documentation site.
// Scans src/ for class/interface/trait/enum declarations and emits a
// Markdown fragment with {{< repoFileURL "src/…" >}} links.
//
// Output: stdout (fragment, no frontmatter)
// Target: assets/includes/linkenhancer/class-hierarchy.md (in wt-modules)
//
// Run: php util/generate-class-hierarchy.php > /path/to/assets/includes/linkenhancer/class-hierarchy.md

declare(strict_types=1);

$srcDir = dirname(__DIR__) . '/src';

if (!is_dir($srcDir)) {
    fwrite(STDERR, "ERROR: src/ not found at {$srcDir}\n");
    exit(1);
}

$rii     = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($srcDir, FilesystemIterator::SKIP_DOTS));
$classes = [];

foreach ($rii as $file) {
    if ($file->getExtension() !== 'php') {
        continue;
    }
    $content = (string) file_get_contents($file->getPathname());
    $rel     = substr($file->getPathname(), strlen($srcDir) + 1);

    // Find ALL top-level declarations (a file may contain class + enum, etc.).
    if (!preg_match_all('/^(final\s+|abstract\s+)?(class|interface|trait|enum)\s+(\w+)/m', $content, $matches, PREG_OFFSET_CAPTURE)) {
        continue;
    }

    foreach ($matches[0] as $idx => $m0) {
        $start = (int) $m0[1];

        // Body starts at the first { or ; after this declaration.
        $bodyPos = strpos($content, '{', $start);
        $semiPos = strpos($content, ';', $start);
        if ($semiPos !== false && ($bodyPos === false || $semiPos < $bodyPos)) {
            $bodyPos = $semiPos;
        }
        if ($bodyPos === false) {
            $bodyPos = strlen($content);
        }

        $chunk = substr($content, $start, $bodyPos - $start);

        $extends    = null;
        $implements = [];
        $uses       = [];

        if (preg_match('/\bextends\s+([\w\\\\]+)/', $chunk, $e)) {
            $extends = $e[1];
        }
        if (preg_match('/\bimplements\s+(.+?)(?=\s*(?:$|\{))/s', $chunk, $i)) {
            $implements = array_values(array_filter(array_map(
                fn(string $s): string => trim(str_replace(["\n", "\t", " "], '', $s)),
                explode(',', $i[1])
            )));
        }
        if (preg_match('/\buses\s+(.+?)(?=\s*(?:$|\{))/s', $chunk, $u)) {
            $uses = array_values(array_filter(array_map(
                fn(string $s): string => trim(str_replace(["\n", "\t", " "], '', $s)),
                explode(',', $u[1])
            )));
        }

        $classes[] = [
            'type'       => $matches[2][$idx][0],
            'name'       => $matches[3][$idx][0],
            'modifiers'  => trim($matches[1][$idx][0] ?? ''),
            'extends'    => $extends,
            'implements' => $implements,
            'uses'       => $uses,
            'file'       => $rel,
            'dir'        => dirname($rel) === '.' ? '' : dirname($rel),
        ];
    }
}

// Group by directory.
$groupOrder = [
    'Services'             => 'Services',
    'Http/RequestHandlers' => 'Request Handlers',
    'Http'                 => 'HTTP',
    'Schema'               => 'Schema',
    'DataFix'              => 'DataFix',
    'DataFix/Handlers'     => 'DataFix Handlers',
    'CommonMark'           => 'CommonMark',
    'Factories'            => 'Factories',
    ''                     => 'Module Root',
];

$groups = [];
foreach ($classes as $c) {
    $label = $groupOrder[$c['dir']] ?? $c['dir'];
    $groups[$label][] = $c;
}

// Deterministic group order: known groups first (in defined order), then extras alphabetically.
$orderedLabels = [];
foreach ($groupOrder as $dir => $label) {
    if (isset($groups[$label])) {
        $orderedLabels[] = $label;
    }
}
$extraLabels = array_values(array_diff(array_keys($groups), $orderedLabels));
usort($extraLabels, 'strcmp');
$allLabels = array_merge($orderedLabels, $extraLabels);

// Emit fragment (no frontmatter).
echo "_Auto-generated by `util/generate-class-hierarchy.php` — do not edit manually._\n\n";

foreach ($allLabels as $label) {
    if (!isset($groups[$label])) {
        continue;
    }
    $items = $groups[$label];
    usort($items, fn(array $a, array $b): int => strcmp($a['name'], $b['name']));

    echo "## {$label}\n\n";
    foreach ($items as $c) {
        $line = '- `' . $c['name'] . '`';
        if ($c['modifiers'] !== '') {
            $line .= ' (' . $c['modifiers'] . ')';
        }
        if ($c['extends'] !== null) {
            $line .= ' extends `' . $c['extends'] . '`';
        }
        if ($c['implements'] !== []) {
            $line .= ' implements `' . implode('`, `', $c['implements']) . '`';
        }
        if ($c['uses'] !== []) {
            $line .= ' uses `' . implode('`, `', $c['uses']) . '`';
        }
        $line .= ' — {{< repoFileURL "src/' . $c['file'] . '" >}}';
        echo $line . "\n";
    }
    echo "\n";
}
